import io
import csv
from services.review_service import get_all_events, get_all_deadlines, get_all_conflicts, get_all_gaps

def generate_markdown_report() -> str:
    events = sorted(get_all_events(), key=lambda x: x.date or "9999-99-99")
    deadlines = get_all_deadlines()
    conflicts = get_all_conflicts()
    gaps = get_all_gaps()

    md = []
    md.append("# CaseCompass - Executive Case Intelligence Report")
    md.append("Generated by CaseCompass Engine\n")
    md.append("## 1. Chronological Case Timeline")
    for e in events:
        status_symbol = "[✓]" if e.review_status == "verified" else "[!]" if e.review_status == "flagged" else "[?]"
        md.append(f"- **{e.date or 'Unknown Date'}** {status_symbol} **{e.title}**")
        md.append(f"  *Source*: {e.document_name} | *Snippet*: \"{e.source_snippet}\"\n")

    md.append("## 2. Key Deadlines")
    for d in deadlines:
        md.append(f"- **{d.due_date}** [{d.urgency.upper()}]: {d.title} ({d.document_name})")

    md.append("\n## 3. Detected Inconsistencies & Conflicts")
    for c in conflicts:
        md.append(f"- **{c.topic}** (Severity: {c.severity.upper()}):")
        md.append(f"  - Option A: {c.date_a} from {c.source_a}")
        md.append(f"  - Option B: {c.date_b} from {c.source_b}")

    md.append("\n## 4. Missing Record Alerts")
    for g in gaps:
        md.append(f"- **{g.title}** (Referenced in {g.referenced_in})")

    return "\n".join(md)

def generate_csv_report() -> str:
    events = sorted(get_all_events(), key=lambda x: x.date or "9999-99-99")
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["ID", "Date", "Raw Date", "Title", "Document", "Review Status", "Is Deadline", "Snippet"])
    for e in events:
        writer.writerow([
            e.id, e.date, e.raw_date_text, e.title, e.document_name, e.review_status, e.is_deadline, e.source_snippet
        ])
    return output.getvalue()
